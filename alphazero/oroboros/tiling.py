BASE_TYPES = ["square", "hex", "triangle", "radial"]
TILING_SIZES = [3, 4, 5, 6]
SYMMETRIES = [3, 4, 5, 6]
BOUNDARIES = ["finite", "torus"]
MODIFIERS = ["none", "none", "none", "staircase", "holes", "asymmetric"]  # biased toward none
MOD_PARAMS = [0, 1, 2]


# ── Factory ───────────────────────────────────────────────────────────────────

def generate_topology(spec: TilingSpec) -> Topology:
    """Generate a topology from a tiling specification."""
    # Base topology
    wrap = spec.boundary == "torus"
    if spec.base == "square":
        topo = _regular_square(spec.size, wrap)
    elif spec.base == "hex":
        topo = _regular_hex(spec.size, wrap)
    elif spec.base == "triangle":
        topo = _regular_triangle(spec.size, wrap)
    elif spec.base == "radial":
        topo = _radial(spec.symmetry, spec.size, notches=True)
    else:
        topo = _regular_hex(spec.size, wrap)

    # Apply modifier
    if spec.modifier == "staircase" and spec.mod_param > 0:
        topo = _apply_staircase(topo, spec.mod_param)
    elif spec.modifier == "holes":
        topo = _apply_holes(topo, 0.15, seed=spec.mod_param)
    elif spec.modifier == "asymmetric" and spec.mod_param > 0:
        topo = _apply_asymmetric(topo, spec.mod_param)

    # Ensure non-empty
    if not topo.nodes:
        topo = _regular_hex(3, False)

    return topo
